function generatePieChart(name: string): string {
  return joinLines([
    `'use client';`,
    ``,
    `import type { DateRange, Row } from '../types';`,
    ``,
    `export interface ${name}Props {`,
    `  id?: string;`,
    `  title?: string;`,
    `  labelField?: string;`,
    `  valueField?: string;`,
    `  donut?: boolean;`,
    `  data: Row[];`,
    `  range?: DateRange;`,
    `}`,
    ``,
    `export function ${name}({`,
    `  id,`,
    `  title = 'Chart',`,
    `  labelField = 'label',`,
    `  valueField = 'value',`,
    `  donut = false,`,
    `  data,`,
    `  range,`,
    `}: ${name}Props) {`,
    `  const points = filterByRange(data, range);`,
    `  const total = points.reduce((sum, row) => sum + Number(row[valueField] ?? 0), 0) || 1;`,
    `  const colors = ['#3b82f6', '#10b981', '#f59e0b', '#ef4444', '#8b5cf6'];`,
    `  let cumulative = 0;`,
    `  const gradient = points`,
    `    .map((row, index) => {`,
    `      const value = Number(row[valueField] ?? 0);`,
    `      const percent = (value / total) * 100;`,
    `      const start = cumulative;`,
    `      cumulative += percent;`,
    `      return \`\${colors[index % colors.length]} \${start}% \${cumulative}%\`;`,
    `    })`,
    `    .join(', ');`,
    ``,
    `  return (`,
    `    <section className="chart-card" id={id}>`,
    `      <h3>{title}</h3>`,
    `      <div`,
    `        className={donut ? 'pie-chart pie-chart--donut' : 'pie-chart'}`,
    `        style={{ background: \`conic-gradient(\${gradient || '#d1d5db 0 100%'})\` }}`,
    `      />`,
    `      <ul className="pie-chart__legend">`,
    `        {points.map((row, index) => (`,
    `          <li key={String(row.id ?? index)}>`,
    `            <span style={{ background: colors[index % colors.length] }} />`,
    `            {String(row[labelField] ?? row.id ?? index)}`,
    `          </li>`,
    `        ))}`,
    `      </ul>`,
    `    </section>`,
    `  );`,
    `}`,
    ``,
    `function filterByRange(data: Row[], range?: DateRange): Row[] {`,
    `  if (!range) {`,
    `    return data;`,
    `  }`,
    `  return data.filter((row) => {`,
    `    const value = String(row.date ?? row.createdAt ?? '');`,
    `    if (!value) {`,
    `      return true;`,
    `    }`,
    `    return value >= range.start && value <= range.end;`,
    `  });`,
    `}`,
    ``,
  ]);
}

