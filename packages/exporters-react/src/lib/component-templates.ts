function generateDateRangeFilter(name: string): string {
  return joinLines([
    `'use client';`,
    ``,
    `import type { DateRange } from '../types';`,
    ``,
    `export interface ${name}Props {`,
    `  id?: string;`,
    `  preset?: string;`,
    `  value?: DateRange;`,
    `  onChange?: (range: DateRange) => void;`,
    `}`,
    ``,
    `export function ${name}({ id, preset = 'last-7-days', value, onChange }: ${name}Props) {`,
    `  const current = value ?? defaultRangeForPreset(preset);`,
    ``,
    `  return (`,
    `    <div className="date-range" id={id}>`,
    `      <label className="field">`,
    `        <span>Start</span>`,
    `        <input`,
    `          className="input"`,
    `          type="date"`,
    `          value={current.start}`,
    `          onChange={(event) => onChange?.({ ...current, start: event.target.value })}`,
    `        />`,
    `      </label>`,
    `      <label className="field">`,
    `        <span>End</span>`,
    `        <input`,
    `          className="input"`,
    `          type="date"`,
    `          value={current.end}`,
    `          onChange={(event) => onChange?.({ ...current, end: event.target.value })}`,
    `        />`,
    `      </label>`,
    `    </div>`,
    `  );`,
    `}`,
    ``,
    `function defaultRangeForPreset(preset: string): DateRange {`,
    `  const end = new Date();`,
    `  const start = new Date(end);`,
    `  if (preset === 'last-30-days') {`,
    `    start.setDate(end.getDate() - 30);`,
    `  } else if (preset === 'qtd') {`,
    `    start.setMonth(Math.floor(end.getMonth() / 3) * 3, 1);`,
    `  } else {`,
    `    start.setDate(end.getDate() - 7);`,
    `  }`,
    `  return { start: formatDate(start), end: formatDate(end) };`,
    `}`,
    ``,
    `function formatDate(date: Date): string {`,
    `  return date.toISOString().slice(0, 10);`,
    `}`,
    ``,
  ]);
}

